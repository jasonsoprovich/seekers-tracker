const SLOW_REQUEST_MS = 5000;
const REQUEST_DEADLINE_MS = 25_000;

function hangResponse(): Response {
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="refresh" content="3"><title>Seekers of Souls</title></head><body style="margin:0;min-height:100vh;display:flex;align-items:center;justify-content:center;background:#0a0a0a;color:#e5e5e5;font-family:ui-sans-serif,system-ui,sans-serif"><div style="max-width:420px;padding:2rem;text-align:center"><h1 style="font-size:1.25rem;font-weight:700">The site took too long to respond</h1><p style="margin-top:.75rem;color:#a3a3a3;font-size:.9rem">Retrying automatically in a few seconds. If this keeps happening, let a leader know.</p><p style="margin-top:1.5rem"><a href="javascript:location.reload()" style="border-radius:9999px;background:#10b981;color:#000;padding:.5rem 1.25rem;font-weight:600;text-decoration:none">Reload now</a></p></div></body></html>`;
  return new Response(html, {
    status: 503,
    headers: { "content-type": "text/html; charset=utf-8", "cache-control": "private, no-cache, no-store, max-age=0, must-revalidate", "retry-after": "3" },
  });
}

const CANONICAL_HOST = "seekersofsouls.com";
const REDIRECT_HOSTS = new Set(["www.seekersofsouls.com", "seekers.fetchinglogic.com", "www.fetchinglogic.com"]);

function canonicalRedirect(request: Request, url: URL): Response | null {
  if (!REDIRECT_HOSTS.has(url.hostname)) return null;
  const target = new URL(url.toString());
  target.hostname = CANONICAL_HOST;
  target.protocol = "https:";
  target.port = "";
  // 308 for non-idempotent methods so a POST (a login submit, an officer
  // API call from a not-yet-updated parser) keeps its method, body, and
  // headers across the hop instead of being downgraded to GET.
  const status = request.method === "GET" || request.method === "HEAD" ? 301 : 308;
  return new Response(null, { status, headers: { Location: target.toString() } });
}

// The "collected by" label on a live-bids card (post-live-test-1 LT-07).
// Prefer the officer's own main character name over their Discord username
// — members recognise "collected by Sandrian", not a Discord handle. The
// parser also sends the exact character whose log it parsed
// (`capturedByCharacter`); when present that wins, since an officer may be
// running an alt. Falls back to the username, then a generic label.
// NOTE (2026-09-10): the "short private browser cache" that used to sit
// here (Cache-Control: private, max-age=15, stale-while-revalidate=60 on
// /roster, /dashboard, /epgp/ledger, ...) is GONE, deliberately. A Next
// client-side navigation is an RSC fetch, and when (app)/layout.tsx throws
// redirect("/login") during one of those the response is HTTP **200** with
// the redirect inside the flight payload — so a single transient "no
// session" (a cold-isolate blip, or one genuine lapse) got "go to /login"
// cached in the viewer's browser for that page for up to 75s. They'd log
// back in, click the same page, replay the cached redirect, and land on
// /login again — the "it keeps logging me out" loop, visible in the
// sessions table as logins seconds apart. Verified live with
// `curl -H 'RSC: 1' /roster` → 200 + that cache header. Speed comes from
// the server-side fixes (batched writes, standings cache), not from
// caching auth-gated responses in the browser.

async function resolveCollectedByName(db: ReturnType<typeof drizzle>, userId: string): Promise<string> {
  const [main] = await db
    .select({ name: characters.name })
    .from(characters)
    .where(and(eq(characters.ownerId, userId), eq(characters.charType, "main")))
    .limit(1);
  if (main?.name?.trim()) return main.name.trim();
  const [row] = await db.select({ username: users.username }).from(users).where(eq(users.id, userId));
  return row?.username?.trim() || "An officer";
}

function collectedByFromBody(body: Record<string, unknown>, fallback: string): string {
  const c = body.capturedByCharacter;
  return typeof c === "string" && c.trim() ? c.trim() : fallback;
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);

    // Phase 4 perf spike (LT-26): PERF_DEBUG=1 turns on [perf] timing logs
    // across getSession / the layout gate / getStandings. One boolean flip
    // per isolate; a no-op otherwise.
    setPerfEnabled((env as { PERF_DEBUG?: string }).PERF_DEBUG === "1");
    markRequest(url.pathname);

    const redirect = canonicalRedirect(request, url);
    if (redirect) return redirect;

    if (url.pathname === "/api/live-bids/ws") return handleLiveBidsWebSocket(request, env);
    if (url.pathname === "/api/live-bids/state" && request.method === "GET") return handleLiveBidsState(request, env);
    if (url.pathname === "/api/live-bids/dismiss" && request.method === "POST") return handleLiveBidsDismiss(request, env);

    const officer = url.pathname.match(/^\/api\/officer\/live-bids\/(push|heartbeat|clear|resolve)$/);
    if (officer && request.method === "POST") return handleOfficerLiveBids(request, env, officer[1]);

    // Always-on slow-request log (2026-09-10): a leader reported the site
    // "freezing" for 60s+ on a page load. Analytics can't tell a hung page
    // render from a long-lived WebSocket, so any non-WS request over
    // SLOW_REQUEST_MS is logged with its path, status and whether the
    // request carried a session cookie — visible in `wrangler tail` and the
    // dashboard's Workers Logs without flipping PERF_DEBUG.
    const t0 = Date.now();
    let status = 0;
    // Request deadline (2026-09-11). Workers Logs showed page renders and
    // officer API reads from three different members' networks held open
    // for 40s to 100 minutes and then "canceled" — a member whose
    // navigation fetch never returns sees a frozen tab, and Next's router
    // has no timeout of its own. There are no Suspense/loading boundaries
    // in this app, so handler.fetch doesn't resolve until the whole render
    // has, which makes a deadline on it meaningful. GET/HEAD only: a
    // timed-out write must not be retried blindly. The 503 is HTML for
    // both document and RSC requests — Next's router hard-navigates on a
    // non-RSC response, so a stuck client-side navigation becomes a fresh
    // full page load; a document request gets the same page, which
    // reloads itself. The [hang] stage/D1 lines logged in the meantime say
    // where it was stuck.
    const deadlineMs = request.method === "GET" || request.method === "HEAD" ? REQUEST_DEADLINE_MS : 0;
    let deadlineTimer: ReturnType<typeof setTimeout> | undefined;
    const deadline = deadlineMs
      ? new Promise<Response>((resolve) => {
          deadlineTimer = setTimeout(() => {
            const rsc = request.headers.has("RSC") ? " rsc" : "";
            console.warn(`[hang] ${request.method} ${url.pathname} no response after ${deadlineMs}ms; returning 503${rsc}`);
            resolve(hangResponse());
          }, deadlineMs);
        })
      : null;
    try {
      const resp = deadline ? await Promise.race([handler.fetch(request, env, ctx), deadline]) : await handler.fetch(request, env, ctx);
      status = resp.status;
      return resp;
    } catch (e) {
      status = -1;
      throw e;
    } finally {
      if (deadlineTimer) clearTimeout(deadlineTimer);
      const ms = Date.now() - t0;
      if (perfEnabled()) console.log(`[perf] request ${request.method} ${url.pathname} ${ms}ms`);
      if (ms >= SLOW_REQUEST_MS) {
        const hasCookie = (request.headers.get("cookie") ?? "").includes("better-auth.session");
        const rsc = request.headers.has("RSC") ? " rsc" : "";
        console.warn(`[slow] ${request.method} ${url.pathname} ${ms}ms status=${status} session=${hasCookie ? "yes" : "no"}${rsc}`);
      }
    }
  },

  // Two crons (wrangler.jsonc `triggers.crons`), dispatched on event.cron.
  async scheduled(event, env, ctx) {
    // "*/2 * * * *" — keep-warm ping (LT-26/LT-27; 2 min since 2026-09-10).
    // Warm the D1 binding on THIS isolate, then self-fetch the health route
    // and an app page so a render-path isolate stays hot too. Best-effort;
    // a failure just means the next real request pays a cold start.
    if (event.cron === "*/2 * * * *") {
      const warm = (async () => {
        try {
          await drizzle(env.DATABASE, { schema }).run(sql`SELECT 1`);
          // Two self-fetches: the API path, and a real app page. Next loads
          // each route's module chunk lazily, so a warm /api/health alone
          // still left the first /roster click paying that route's own
          // module evaluation + the layout/auth chain. /roster without a
          // cookie is a cheap 307 (getSession → null → redirect) that
          // evaluates exactly those modules. "manual" redirect so the
          // fetch doesn't follow it into /login.
          const [h, p] = await Promise.all([
            fetch("https://seekersofsouls.com/api/health", { headers: { "x-warm": "cron" } }),
            fetch("https://seekersofsouls.com/roster", { headers: { "x-warm": "cron" }, redirect: "manual" }),
          ]);
          console.log(`[cron] warm ping health=${h.status} page=${p.status}`);
        } catch (e) {
          console.log(`[cron] warm ping failed: ${e}`);
        }
      })();
      ctx.waitUntil(warm);
      return;
    }

    // "17 9 * * *" — nightly safety-net rebuild. refreshStandings already
    // runs on every write, so this only catches a missed hook or the
    // per-cycle-rollover shift under decay_model=legacy — and, via
    // rebuildAllStandings, re-derives characters.last_activity_at too.
    const db = drizzle(env.DATABASE, { schema });
    const { players } = await rebuildAllStandings(db);
    console.log(`[cron] rebuilt standings + last_activity for ${players} players`);

    // Prune expired session rows. better-auth's session.create.after hook
    // mints a fresh `sessions` row on every login and nothing ever deletes
    // them, so the table grows one row per login forever (84 rows / 11
    // users as of 2026-09-09, ~half already expired). Nothing reads an
    // expired row — better-auth filters on expires_at itself — this just
    // keeps the table from accreting dead rows indefinitely. Best-effort:
    // a failure here must not fail the standings rebuild above.
    try {
      const res = await db.run(
        sql`DELETE FROM sessions WHERE expires_at < strftime('%s','now')`,
      );
      console.log(`[cron] pruned ${res.meta.changes ?? 0} expired session rows`);
    } catch (e) {
      console.log(`[cron] session prune failed (non-fatal): ${e}`);
    }

    // Re-derive characters.char_type/main_character_id from
    // players.main_character_id (see reconcileMainPointers). Anything other
    // than zeros here means some write path let the two drift again — worth
    // a look at who edited what that day.
    try {
      const r = await reconcileMainPointers(db);
      console.log(`[cron] main-pointer reconcile: alts=${r.altsRetyped} mains=${r.mainsRetyped} pointers=${r.pointersSet}`);
    } catch (e) {
      console.log(`[cron] main-pointer reconcile failed (non-fatal): ${e}`);
    }
  },
} satisfies ExportedHandler<CloudflareEnv>;

