// Wraps the OpenNext-generated worker to also export our own Durable
// Object (PLAN.md §15 / Phase 12) — `.open-next/worker.js` is regenerated
// on every build and has no way to know about app-level bindings, so this
// file (pointed at by `main` in wrangler.jsonc / wrangler.dev.jsonc) is
// the one that doesn't get overwritten.
// See https://opennext.js.org/cloudflare/howtos/custom-worker.
//
// It also handles ALL of the live-bids traffic directly, ahead of Next:
//
//  - `/api/live-bids/ws` — a Next Route Handler can't return the 101
//    upgrade (OpenNext bridges API routes through a Node-ServerResponse
//    shim that rejects any status outside 200-599), so this has always
//    been here.
//  - `/api/live-bids/state` and `/api/officer/live-bids/{push,heartbeat,
//    clear}` moved here 2026-08-30. They call the LiveAuctionSession
//    Durable Object, and doing that *from Next server code* is a double
//    hop under OpenNext local dev — workerd → the Node loopback that runs
//    Next → back to workerd for the DO RPC — which can't sustain the
//    parser app's poll loop and takes `wrangler dev` down with it (see
//    CLAUDE.md "Hard-won gotchas"). Handled here, the DO RPC never leaves
//    workerd. Also one less hop in production. Auth is the same — the
//    officer x-api-key check and the session+membership check — just
//    invoked with `env` directly instead of via getCloudflareContext().
//
// The finalize path (`POST /api/officer/bids`) still calls the DO's
// /clear from its Next route: that's one call per round, not a loop, so it
// doesn't have the sustained-load problem.

