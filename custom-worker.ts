function cfOf(request: Request) {
  return (request as unknown as { cf?: Record<string, unknown> }).cf;
}

async function handleLiveBidsWebSocket(request: Request, env: CloudflareEnv): Promise<Response> {
  if (request.headers.get("Upgrade") !== "websocket") {
    return new Response("Expected a WebSocket upgrade", { status: 426 });
  }

  const auth = createAuth(env, cfOf(request));
  const session = await auth.api.getSession({ headers: request.headers });
  if (!session) {
    return Response.json({ error: "Not signed in." }, { status: 401 });
  }

  const db = drizzle(env.DATABASE, { schema });
  if (!(await fetchIsMemberAllowed(db, session.user.id))) {
    return Response.json({ error: "Access denied." }, { status: 403 });
  }

  // Pass the resolved user id to the DO so it can filter this viewer's
  // dismissed rounds out of every frame on this socket (LT-32). The second
  // arg copies method + the Upgrade headers; the URL comes from the first.
  const stub = liveAuctionStub(env);
  const doUrl = `https://live-auction-session/ws?userId=${encodeURIComponent(session.user.id)}`;
  return stub.fetch(new Request(doUrl, request));
}

// GET /api/live-bids/state — every member (same bar as the WS view).
async function handleLiveBidsState(request: Request, env: CloudflareEnv): Promise<Response> {
  const auth = createAuth(env, cfOf(request));
  const session = await auth.api.getSession({ headers: request.headers });
  if (!session) return Response.json({ error: "Not signed in." }, { status: 401 });

  const db = drizzle(env.DATABASE, { schema });
  if (!(await fetchIsMemberAllowed(db, session.user.id))) {
    return Response.json({ error: "Not allowed." }, { status: 403 });
  }

  // ?userId= so the DO's snapshot already has this viewer's dismissed
  // rounds (LT-32) filtered out — same view the WS frames give them.
  const doUrl = `https://live-auction-session/state?userId=${encodeURIComponent(session.user.id)}`;
  const resp = await liveAuctionStub(env).fetch(doUrl);
  if (!resp.ok) return Response.json({ error: "Live session unavailable." }, { status: 502 });
  return new Response(await resp.text(), { headers: { "Content-Type": "application/json" } });
}

// POST /api/live-bids/dismiss — every member (same bar as /state). LT-32:
// this is the member-facing "Dismiss" on a resolved card, and it's now a
// PER-ACCOUNT dismiss — the DO records it against this viewer's user id
// (persisted, survives their refresh and a DO eviction) and keeps showing
// the round to everyone else. It clears itself when the round leaves the
// board (12h auto-sweep, a re-drop of the same item, or an officer /clear).
// The old localStorage-only client hack is gone. Forwarding without a
// `userId` still triggers the DO's legacy global force-clear, but nothing
// does that now.
async function handleLiveBidsDismiss(request: Request, env: CloudflareEnv): Promise<Response> {
  const auth = createAuth(env, cfOf(request));
  const session = await auth.api.getSession({ headers: request.headers });
  if (!session) return Response.json({ error: "Not signed in." }, { status: 401 });

  const db = drizzle(env.DATABASE, { schema });
  if (!(await fetchIsMemberAllowed(db, session.user.id))) {
    return Response.json({ error: "Not allowed." }, { status: 403 });
  }

  let itemName: unknown;
  let all: unknown;
  try {
    ({ itemName, all } = (await request.json()) as { itemName?: unknown; all?: unknown });
  } catch {
    return Response.json({ error: "Invalid JSON body." }, { status: 400 });
  }
  // `all: true` — the board's "Clear all" (2026-09-10): dismiss every
  // resolved card for this viewer in one call.
  if (all === true) return forwardToDO(env, "dismiss", { all: true, userId: session.user.id });
  if (typeof itemName !== "string" || !itemName.trim()) {
    return Response.json({ error: "`itemName` is required." }, { status: 400 });
  }
  return forwardToDO(env, "dismiss", { itemName: itemName.trim(), userId: session.user.id });
}

// POST /api/officer/live-bids/{push,heartbeat,clear,resolve} — officer x-api-key.
async function handleOfficerLiveBids(request: Request, env: CloudflareEnv, action: string): Promise<Response> {
  const auth = await verifyOfficerApiKey(request, env, cfOf(request));
  if ("error" in auth) return Response.json({ error: auth.error }, { status: auth.status });

  const db = drizzle(env.DATABASE, { schema });
  const officerName = await resolveCollectedByName(db, auth.userId);

  let body: Record<string, unknown> = {};
  try {
    body = (await request.json()) as Record<string, unknown>;
  } catch {
    if (action === "push" || action === "resolve") return Response.json({ error: "Invalid JSON body." }, { status: 400 });
    // heartbeat/clear tolerate an empty body
  }

  if (action === "push") {
    if (typeof body.itemName !== "string" || !body.itemName.trim()) {
      return Response.json({ error: "`itemName` is required." }, { status: 400 });
    }

    // Snapshot push (parser >= v0.1.13): the officer's whole current bid
    // list for this item, every tick — see the DO's /push handler for why.
    // Priority for every name is resolved in ONE roster query (COLLATE
    // NOCASE, matching the characters unique index) + the cached standings.
    if (Array.isArray(body.bids)) {
      const raw = body.bids as unknown[];
      const tells: { characterName: string; tier: string; occurredAt: string }[] = [];
      for (const r of raw.slice(0, 200)) {
        if (!r || typeof r !== "object") continue;
        const b = r as { characterName?: unknown; tier?: unknown; occurredAt?: unknown };
        if (typeof b.characterName !== "string" || !b.characterName.trim()) continue;
        if (typeof b.tier !== "string" || typeof b.occurredAt !== "string") continue;
        if (Number.isNaN(new Date(b.occurredAt).getTime())) continue;
        tells.push({ characterName: b.characterName.trim(), tier: b.tier.trim(), occurredAt: b.occurredAt });
      }
      const priorityByName = new Map<string, number | null>();
      const names = [...new Set(tells.map((t) => t.characterName))];
      if (names.length > 0) {
        const [chars, totals] = await Promise.all([
          db
            .select({ name: characters.name, playerId: characters.playerId })
            .from(characters)
            .where(sql`${characters.name} COLLATE NOCASE IN (${sql.join(names.map((n) => sql`${n}`), sql`, `)})`),
          getStandings(db),
        ]);
        for (const c of chars) {
          priorityByName.set(c.name.toLowerCase(), c.playerId != null ? (totals.get(c.playerId)?.priorityRating ?? null) : null);
        }
      }
      return forwardToDO(env, "push", {
        itemName: (body.itemName as string).trim(),
        bids: tells.map((t) => ({ ...t, priorityRating: priorityByName.get(t.characterName.toLowerCase()) ?? null })),
        officerId: auth.userId,
        officerName: collectedByFromBody(body, officerName),
      });
    }

    for (const f of ["characterName", "tier"] as const) {
      if (typeof body[f] !== "string" || !(body[f] as string).trim()) {
        return Response.json({ error: `\`${f}\` is required.` }, { status: 400 });
      }
    }
    if (typeof body.occurredAt !== "string" || Number.isNaN(new Date(body.occurredAt).getTime())) {
      return Response.json({ error: "`occurredAt` must be a valid date." }, { status: 400 });
    }

    // Best-effort priority — an unmatched name still gets pushed live with
    // priorityRating null rather than dropped (same as the officer's own
    // review table handling a "no match").
    const characterName = (body.characterName as string).trim();
    const [character] = await db.select({ playerId: characters.playerId }).from(characters).where(eq(characters.name, characterName));
    let priorityRating: number | null = null;
    if (character?.playerId != null) {
      const totals = await getStandings(db);
      priorityRating = totals.get(character.playerId)?.priorityRating ?? null;
    }

    return forwardToDO(env, "push", {
      itemName: (body.itemName as string).trim(),
      characterName,
      tier: (body.tier as string).trim(),
      occurredAt: body.occurredAt,
      priorityRating,
      officerId: auth.userId,
      officerName: collectedByFromBody(body, officerName),
    });
  }

  if (action === "resolve") {
    if (typeof body.itemName !== "string" || !body.itemName.trim()) {
      return Response.json({ error: "`itemName` is required." }, { status: 400 });
    }
    // The parser sends the full final bid list (`bids`, every entry flagged
    // isWinner or not) as of 2026-09-01 so the resolved card keeps showing
    // every bidder + priority, not just the winner. Older clients send only
    // `winners` — still supported.
    const rawBids = Array.isArray(body.bids) ? body.bids : [];
    const rawWinners = Array.isArray(body.winners) ? body.winners : [];

    // Prefer the Priority Rating snapshotted at bid time. POST
    // /api/officer/bids runs immediately before this and writes
    // bids.priority_snapshot for every bidder *before* the winner's GP
    // charge lands. If we recomputed PR here from live standings instead,
    // the winner would show post-charge (lower) while the losers stay
    // pre-charge — making the winner look like they had the worst
    // priority on the resolved card. Read the snapshot back, keyed by
    // character name, and only fall back to a live lookup for a name that
    // has no bid row (e.g. an unmatched bid).
    const snapshotByName = new Map<string, number>();
    try {
      const itemLower = body.itemName.trim().toLowerCase();
      const [latestEvent] = await db
        .select({ id: lootEvents.id })
        .from(lootEvents)
        .where(sql`lower(${lootEvents.itemName}) = ${itemLower}`)
        .orderBy(desc(lootEvents.id))
        .limit(1);
      if (latestEvent) {
        const snapRows = await db
          .select({ name: characters.name, snap: bidsTable.prioritySnapshot })
          .from(bidsTable)
          .innerJoin(characters, eq(characters.id, bidsTable.characterId))
          .where(eq(bidsTable.lootEventId, latestEvent.id));
        for (const r of snapRows) if (typeof r.snap === "number") snapshotByName.set(r.name.toLowerCase(), r.snap);
      }
    } catch {
      // best-effort — fall back to the live lookup below
    }

    // Live standings, only fetched if some name has no snapshot to use.
    let totals: Awaited<ReturnType<typeof getStandings>> | null = null;
    const priorityCache = new Map<string, number | null>();
    async function priorityFor(name: string): Promise<number | null> {
      const snap = snapshotByName.get(name.toLowerCase());
      if (snap !== undefined) return snap;
      const cached = priorityCache.get(name.toLowerCase());
      if (cached !== undefined) return cached;
      let priorityRating: number | null = null;
      if (!totals && (rawBids.length || rawWinners.length)) totals = await getStandings(db);
      const [character] = await db.select({ playerId: characters.playerId }).from(characters).where(eq(characters.name, name));
      if (character?.playerId != null && totals) priorityRating = totals.get(character.playerId)?.priorityRating ?? null;
      priorityCache.set(name.toLowerCase(), priorityRating);
      return priorityRating;
    }

    // One row per character, same as the live "collecting" card and the
    // parser's own ResolveLatestPerCharacter: a winner row always wins the
    // slot, otherwise the later entry does (the parser sends them in
    // occurredAt order). Keeps a "changed my mind" / superseded bid from
    // showing as a second row on the resolved card.
    const byName = new Map<string, { characterName: string; tier: string; isWinner: boolean; occurredAt: string | undefined }>();
    for (const b of rawBids) {
      if (!b || typeof b !== "object") continue;
      const cb = b as { characterName?: unknown; tier?: unknown; isWinner?: unknown; occurredAt?: unknown };
      if (typeof cb.characterName !== "string" || typeof cb.tier !== "string") continue;
      const name = cb.characterName.trim();
      const isWinner = cb.isWinner === true;
      const prev = byName.get(name.toLowerCase());
      if (prev && prev.isWinner && !isWinner) continue;
      byName.set(name.toLowerCase(), {
        characterName: name,
        tier: cb.tier.trim(),
        isWinner,
        occurredAt: typeof cb.occurredAt === "string" ? cb.occurredAt : undefined,
      });
    }

    const bids = [];
    const winnersFromBids = [];
    for (const row of byName.values()) {
      const priorityRating = await priorityFor(row.characterName);
      bids.push({ characterName: row.characterName, tier: row.tier, priorityRating, occurredAt: row.occurredAt });
      if (row.isWinner) winnersFromBids.push({ characterName: row.characterName, tier: row.tier, priorityRating });
    }

    // Winners: derived from the bid list's isWinner flags when present,
    // otherwise the legacy explicit `winners` array.
    let winners = winnersFromBids;
    if (winners.length === 0 && rawWinners.length) {
      for (const w of rawWinners) {
        if (!w || typeof w !== "object") continue;
        const cw = w as { characterName?: unknown; tier?: unknown };
        if (typeof cw.characterName !== "string" || typeof cw.tier !== "string") continue;
        const name = cw.characterName.trim();
        winners.push({ characterName: name, tier: cw.tier.trim(), priorityRating: await priorityFor(name) });
      }
    }

    // POST /api/officer/bids ran just before this and charged the winner's
    // GP + refreshed standings, so getStandings() here is current. Every
    // OTHER still-collecting round on the board is showing pre-charge
    // priority for anyone that charge moved — hand the DO a fresh
    // name→priority map so it can re-price those rounds and an officer
    // picking a winner elsewhere doesn't do it off a stale number (which is
    // how one character could sweep several items before EPGP caught up).
    let repriceAll: Record<string, number> | undefined;
    try {
      const s = await getStandings(db);
      const chars = await db.select({ name: characters.name, playerId: characters.playerId }).from(characters);
      const m: Record<string, number> = {};
      for (const c of chars) {
        if (c.playerId == null) continue;
        const pr = s.get(c.playerId)?.priorityRating;
        if (typeof pr === "number") m[c.name.toLowerCase()] = pr;
      }
      repriceAll = m;
    } catch {
      // best-effort — the resolve still goes through without the reprice
    }

    return forwardToDO(env, "resolve", {
      itemName: body.itemName.trim(),
      winners,
      bids,
      repriceAll,
      officerId: auth.userId,
      officerName: collectedByFromBody(body, officerName),
    });
  }

  if (action === "heartbeat") {
    return forwardToDO(env, "heartbeat", {
      itemName: typeof body.itemName === "string" ? body.itemName : undefined,
      officerId: auth.userId,
      officerName,
    });
  }

  // clear — officerId scopes a bare (no itemName) clear to just this
  // officer's rounds, so one officer quitting their app can't wipe every
  // other officer's live round off the board.
  return forwardToDO(env, "clear", {
    itemName: typeof body.itemName === "string" ? body.itemName : undefined,
    officerId: auth.userId,
  });
}

async function forwardToDO(env: CloudflareEnv, path: string, payload: unknown): Promise<Response> {
  try {
    const resp = await liveAuctionStub(env).fetch(`https://live-auction-session/${path}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    if (!resp.ok) return Response.json({ error: "Live session rejected the request." }, { status: 502 });
  } catch {
    return Response.json({ error: "Live session unavailable." }, { status: 502 });
  }
  return Response.json({ ok: true }, { status: 200 });
}

function liveAuctionStub(env: CloudflareEnv) {
  return env.LIVE_AUCTION_SESSION.get(env.LIVE_AUCTION_SESSION.idFromName("global"));
}

// The guild's live domain. seekersofsouls.com (apex) is canonical; every
// other hostname that routes to this Worker in production — www, plus the
// old placeholder seekers.fetchinglogic.com host, kept alive only as a
// redirecting backup — 301/308s here so there's exactly one origin the app,
